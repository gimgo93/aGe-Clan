import assert from 'node:assert/strict';
import {pvpGateway} from '../lib/pvp-gateway.js';
import {RoomDirectory,directoryRecord} from '../lib/room-directory.js';
const origin='https://game.example',cookie='a'.repeat(64),env={CLAN_BACKEND_URL:'https://pvp.example',CLAN_BACKEND_TOKEN:'test-only-'.repeat(4)};
const request=(path='/api/clan',extra={})=>new Request(origin+path,{method:'POST',headers:{origin,cookie:`other=private; clan_session=${cookie}`,'x-clan-key':'forged','x-clan-backend-token':'forged'},body:'{"op":"poll"}',...extra});
assert.equal(await pvpGateway(request(),{}),null);
let forwarded;
const reply=new Response('{"transport":"websocket"}',{headers:{'Set-Cookie':'clan_session='+cookie+'; Path=/api/clan; HttpOnly; Secure; SameSite=Strict'}});
assert.equal(await pvpGateway(request(),env,async r=>{forwarded=r;return reply;}),reply);
assert.equal(forwarded.url,'https://pvp.example/api/clan');
assert.equal(forwarded.headers.get('origin'),'https://pvp.example');
assert.equal(forwarded.headers.get('cookie'),'clan_session='+cookie);
assert.equal(forwarded.headers.get('x-clan-key'),null);
assert.equal(forwarded.headers.get('x-clan-backend-token'),env.CLAN_BACKEND_TOKEN);
assert.equal(forwarded.redirect,'manual');
assert.equal(await forwarded.text(),'{"op":"poll"}');
for(const config of [{...env,CLAN_BACKEND_TOKEN:''},{...env,CLAN_BACKEND_URL:origin},{...env,CLAN_BACKEND_URL:'http://pvp.example'}])assert.equal((await pvpGateway(request(),config,()=>assert.fail())).status,503);
assert.equal((await pvpGateway(request('/api/clan',{headers:{origin:'https://evil.example'}}),env,()=>assert.fail())).status,403);
assert.equal((await pvpGateway(request(),env,async()=>{throw Error('unavailable');})).status,503,'no split-state fallback');
assert.equal((await pvpGateway(request(),env,async()=>new Response(null,{status:302,headers:{location:'https://evil.example'}}))).status,503);
const upgrade={status:101,webSocket:{}};
assert.equal(await pvpGateway(new Request(origin+'/api/clan/socket?roomId=F-TEST',{headers:{origin,upgrade:'websocket',cookie:'clan_session='+cookie}}),env,async r=>{assert.equal(r.headers.get('upgrade'),'websocket');assert.equal(new URL(r.url).searchParams.get('roomId'),'F-TEST');return upgrade;}),upgrade,'preserve upgrade response, never reconstruct status 101');

let release,calls=0,active=0,maxActive=0;const stored=[],tasks=[];
const db={prepare:()=>({bind:(...args)=>({run:async()=>{calls++;active++;maxActive=Math.max(maxActive,active);if(calls===1)await new Promise(r=>release=r);stored.push(args);active--;}})})};
const dir=new RoomDirectory(db,p=>tasks.push(p));
const room={status:'playing',private:true,players:[{key:'hash',entryId:'entry',s:{over:false,enemies:[{large:'payload'}]}}]};
const a=directoryRecord('F-TEST',room,1);assert.equal(JSON.parse(a.state).players[0].s.enemies,undefined,'directory excludes simulation');
dir.enqueue(a);dir.enqueue(directoryRecord('F-TEST',room,2));dir.enqueue(directoryRecord('F-TEST',room,3));
assert.equal(calls,1,'slow D1 does not block room callers or start overlapping writes');
release();await Promise.all(tasks);
assert.equal(maxActive,1);assert.deepEqual(stored.map(x=>x[2]),[1,3],'coalesce obsolete directory versions');
console.log('PASS: authenticated same-origin gateway, cookie isolation, WebSocket upgrade preservation, fail-closed routing, asynchronous/coalesced metadata-only D1');
