import fs from 'node:fs';
import vm from 'node:vm';
import {createHash} from 'node:crypto';
const context={window:{}};
vm.runInNewContext(fs.readFileSync('public/game/balance.js','utf8'),context);
const game=fs.readFileSync('public/game/game.js','utf8');
const body=game.slice(game.indexOf("'use strict';"),game.lastIndexOf('\n});')).replace('return{Game,','const exported={Game,');
fs.writeFileSync('lib/game-engine.js',`// Generated by tools/sync-engine.mjs from public/game/game.js and balance.js.\nconst root={FRONTIER_BALANCE:${JSON.stringify(context.window.FRONTIER_BALANCE)}};\n${body}\nexport default exported;\n`);
const release=JSON.parse(fs.readFileSync('public/game/release.json','utf8'));
const sha=path=>createHash('sha256').update(fs.readFileSync(path,'utf8').replace(/\r\n/g,'\n')).digest('hex');
const releaseInfo={release:release.version,engineSha256:sha('lib/game-engine.js'),balanceSha256:sha('public/game/balance.js')};
fs.writeFileSync('lib/release-info.js','// Generated release provenance; contains no runtime credentials.\nexport const releaseInfo='+JSON.stringify(releaseInfo)+';\n');
